import { test, expect } from './fixtures';

test('CART live item counts, add notification, stock cap, edits and cross-tab updates', async ({ page, request, context }) => {
  const products = await request.get('/api/products').then(response => response.json());
  const product = { ...products.find((item: any) => item.sku === 'CEDAR'), stock: 2 };
  await page.route('**/api/products/CEDAR', route => route.fulfill({ json: product }));
  await page.goto('/shop/CEDAR');
  const navCount = page.locator('.browsing-nav .cart-count-badge');
  const productCount = page.locator('.product-cart-link .cart-count-badge');
  await expect(navCount).toHaveText('0');
  await expect(productCount).toHaveText('0');
  await page.getByRole('button', { name: 'Add to cart', exact: true }).click();
  await expect(navCount).toHaveText('1');
  await expect(productCount).toHaveText('1');
  await expect(page.getByRole('status')).toContainText('Cedar & Smoke added to cart');
  await expect(page.locator('.product-cart-quantity')).toHaveText('1 in your cart');
  await page.getByRole('button', { name: 'Increase quantity', exact: true }).click();
  await expect(navCount).toHaveText('2');
  await expect(page.getByRole('button', { name: 'Increase quantity', exact: true })).toBeDisabled();
  await expect(productCount).toHaveText('2');
  const stepper = await page.locator('.product-quantity-stepper').boundingBox();
  const cartButton = await page.locator('.product-cart-link').boundingBox();
  expect(Math.abs(stepper!.y - cartButton!.y)).toBeLessThan(1);
  expect(Math.abs(stepper!.height - cartButton!.height)).toBeLessThan(1);
  await page.screenshot({ path: test.info().outputPath('cart-feedback.png'), fullPage: true });
  await page.reload();
  await expect(productCount).toHaveText('2');
  await expect(page.getByRole('status')).toBeEmpty();
  await page.getByRole('button', { name: 'Decrease quantity' }).click();
  await expect(productCount).toHaveText('1');
  await page.getByRole('button', { name: 'Decrease quantity' }).click();
  await expect(productCount).toHaveText('0');
  await expect(page.getByRole('button', { name: 'Add to cart', exact: true })).toBeFocused();
  await page.getByRole('button', { name: 'Add to cart', exact: true }).click();
  await page.getByRole('button', { name: 'Increase quantity' }).click();
  await page.locator('.product-cart-link').click();
  await page.getByRole('spinbutton').fill('1');
  await expect(navCount).toHaveText('1');
  await page.getByRole('button', { name: 'Remove', exact: true }).click();
  await expect(navCount).toHaveText('0');

  const second = await context.newPage();
  await second.goto('/shop/FIG');
  await second.getByRole('button', { name: 'Add to cart', exact: true }).click();
  await expect(navCount).toHaveText('1');
  await expect(page.getByRole('spinbutton')).toHaveValue('1');
  await page.getByRole('button', { name: 'Clear', exact: true }).click();
  await expect(navCount).toHaveText('0');
  await expect(second.locator('.product-cart-link .cart-count-badge')).toHaveText('0');
  await second.close();
});
